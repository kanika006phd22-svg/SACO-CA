import numpy as np
import random
import matplotlib.pyplot as plt

# -----------------------------
# Network Parameters
# -----------------------------
NUM_NODES = 100
AREA_SIZE = 100
MAX_ITER = 100
DIM = 2  # x, y position
INITIAL_ENERGY = 1.0

# -----------------------------
# Initialize Nodes
# -----------------------------
nodes = np.random.rand(NUM_NODES, DIM) * AREA_SIZE
energy = np.ones(NUM_NODES) * INITIAL_ENERGY

# -----------------------------
# Fitness Function
# -----------------------------
def fitness_function(position, energy, nodes):
    # Distance to centroid
    centroid = np.mean(nodes, axis=0)
    dist = np.linalg.norm(position - centroid)

    # Energy factor
    energy_factor = np.mean(energy)

    # Balanced fitness
    fitness = dist / (energy_factor + 1e-6)
    return fitness

# -----------------------------
# Initialize Population
# -----------------------------
def initialize_population(pop_size):
    return np.random.rand(pop_size, DIM) * AREA_SIZE

# -----------------------------
# SACO-CA Algorithm
# -----------------------------
def SACO_CA(pop_size):
    population = initialize_population(pop_size)
    fitness = np.array([fitness_function(p, energy, nodes) for p in population])

    best_idx = np.argmin(fitness)
    best_solution = population[best_idx]
    best_fitness = fitness[best_idx]

    fitness_history = []

    for iter in range(MAX_ITER):

        for i in range(pop_size):

            RN2, RN3 = random.random(), random.random()

            if RN2 < RN3:
                RN4 = np.random.normal(0, 1)

                if fitness[i] >= RN4:
                    # Searching behavior
                    step = np.random.uniform(-1, 1, DIM)
                    population[i] += step
                else:
                    # Attacking behavior
                    population[i] += 0.5 * (best_solution - population[i])

            else:
                # Sit-and-wait
                population[i] += 0.1 * np.random.uniform(-1, 1, DIM)

            # Boundary control
            population[i] = np.clip(population[i], 0, AREA_SIZE)

        # Recalculate fitness
        fitness = np.array([fitness_function(p, energy, nodes) for p in population])

        # Update best solution
        current_best_idx = np.argmin(fitness)
        if fitness[current_best_idx] < best_fitness:
            best_solution = population[current_best_idx]
            best_fitness = fitness[current_best_idx]

        fitness_history.append(best_fitness)

    return best_solution, best_fitness, fitness_history

best_sol, best_fit, history = SACO_CA(pop_size=30)

print("Best Control Node Position:", best_sol)
print("Best Fitness:", best_fit)

plt.figure()
plt.plot(history)
plt.title("SACO-CA Convergence Curve")
plt.xlabel("Iterations")
plt.ylabel("Fitness")
plt.grid()
plt.show()



import numpy as np
import matplotlib.pyplot as plt

# ============================================================
# SACO-CA: Underwater SD-FSO-UWSN Simulation
# Alive/Dead Nodes and Residual Energy
# ============================================================

np.random.seed(42)

# ------------------------------------------------------------
# 1. NETWORK PARAMETERS
# ------------------------------------------------------------

N = 500                    # Number of underwater sensor nodes
AREA_X = 1000              # Deployment area (m)
AREA_Y = 1000

MAX_ITER = 300             # Number of communication rounds

INITIAL_ENERGY = 2.0       # Joules per node
PACKET_SIZE = 4000         # bits

# Desired number of Control Nodes
CN_RATIO = 0.08
NUM_CN = max(5, int(N * CN_RATIO))

# ------------------------------------------------------------
# 2. FSO / ENERGY MODEL PARAMETERS
# ------------------------------------------------------------

E_ELEC = 50e-9             # J/bit
E_AMP = 0.8e-12            # Amplifier coefficient
E_DA = 5e-9                # Data aggregation energy

# FSO optical parameters
FSO_BASE_ENERGY = 0.25e-3
FSO_DISTANCE_FACTOR = 0.000004

# Maximum effective optical communication distance
D_MAX = 450.0

# ------------------------------------------------------------
# 3. SACO-CA FITNESS WEIGHTS
# ------------------------------------------------------------

W_ENERGY = 0.35
W_DISTANCE = 0.25
W_BALANCE = 0.20
W_LINK = 0.20

# ------------------------------------------------------------
# 4. INITIAL NODE DEPLOYMENT
# ------------------------------------------------------------

positions = np.column_stack((
    np.random.uniform(0, AREA_X, N),
    np.random.uniform(0, AREA_Y, N)
))

energy = np.ones(N) * INITIAL_ENERGY

# Control/server location
CONTROL_SERVER = np.array([AREA_X / 2, AREA_Y / 2])

# ------------------------------------------------------------
# 5. STORAGE FOR RESULTS
# ------------------------------------------------------------

alive_history = []
dead_history = []
residual_energy_history = []
cn_history = []

first_dead_round = None
half_dead_round = None
last_alive_round = None

# ------------------------------------------------------------
# 6. DISTANCE MATRIX
# ------------------------------------------------------------

def distance_matrix(nodes):
    diff = nodes[:, None, :] - nodes[None, :, :]
    return np.sqrt(np.sum(diff ** 2, axis=2))


DIST = distance_matrix(positions)

# ------------------------------------------------------------
# 7. FSO LINK QUALITY
# ------------------------------------------------------------

def optical_link_quality(distance):

    # Exponential attenuation model
    attenuation = np.exp(-distance / 300.0)

    # Additional distance-dependent degradation
    quality = attenuation * np.exp(-(distance / D_MAX) ** 2)

    return np.clip(quality, 0.0, 1.0)


# ------------------------------------------------------------
# 8. SACO-CA FITNESS
# ------------------------------------------------------------

def calculate_fitness(candidate, alive_nodes):

    if len(alive_nodes) <= 1:
        return np.inf

    # Energy component
    energy_component = 1.0 - (
        energy[candidate] / INITIAL_ENERGY
    )

    # Distances from candidate to alive nodes
    distances = DIST[candidate, alive_nodes]

    # Average intra-cluster distance
    avg_distance = np.mean(distances)

    distance_component = min(
        avg_distance / D_MAX, 1.0
    )

    # Cluster balance approximation
    # Candidate should not be excessively far from
    # the average position of active nodes.
    center = np.mean(
        positions[alive_nodes],
        axis=0
    )

    center_distance = np.linalg.norm(
        positions[candidate] - center
    )

    balance_component = min(
        center_distance / (AREA_X * 0.707),
        1.0
    )

    # Average optical link quality
    q = optical_link_quality(distances)
    avg_q = np.mean(q)

    link_component = 1.0 - avg_q

    # Final SACO-CA fitness
    fitness = (
        W_ENERGY * energy_component
        + W_DISTANCE * distance_component
        + W_BALANCE * balance_component
        + W_LINK * link_component
    )

    return fitness


# ------------------------------------------------------------
# 9. SELF-ADAPTIVE CHEETAH SEARCH
# ------------------------------------------------------------

def select_control_nodes(alive_nodes):

    if len(alive_nodes) <= NUM_CN:
        return alive_nodes.copy()

    population_size = min(60, len(alive_nodes))

    # Random candidate population
    population = np.random.choice(
        alive_nodes,
        population_size,
        replace=False
    )

    # Evaluate fitness
    fitness_values = np.array([
        calculate_fitness(x, alive_nodes)
        for x in population
    ])

    # Self-adaptive inertia
    inertia = (
        0.9
        - 0.5 * (current_iteration / MAX_ITER)
    )

    # Cheetah-inspired adaptive perturbation
    perturbation_strength = (
        0.05 * (1.0 - current_iteration / MAX_ITER)
        + 0.01
    )

    # Number of local search trials
    local_trials = 3

    improved_candidates = []

    for candidate in population:

        current_fitness = calculate_fitness(
            candidate,
            alive_nodes
        )

        best_candidate = candidate
        best_fitness = current_fitness

        for _ in range(local_trials):

            # Search neighboring nodes
            candidate_position = positions[candidate]

            displacement = (
                np.random.normal(
                    0,
                    perturbation_strength,
                    2
                )
                * np.array([AREA_X, AREA_Y])
            )

            target_position = (
                candidate_position
                + displacement
            )

            target_position[0] = np.clip(
                target_position[0],
                0,
                AREA_X
            )

            target_position[1] = np.clip(
                target_position[1],
                0,
                AREA_Y
            )

            # Find nearest real node to target position
            target_distances = np.linalg.norm(
                positions[alive_nodes] -
                target_position,
                axis=1
            )

            new_candidate = alive_nodes[
                np.argmin(target_distances)
            ]

            new_fitness = calculate_fitness(
                new_candidate,
                alive_nodes
            )

            # Exploitation/exploration decision
            r = np.random.rand()

            if r < inertia:

                # Exploitation
                if new_fitness < best_fitness:
                    best_candidate = new_candidate
                    best_fitness = new_fitness

            else:

                # Exploration
                if np.random.rand() < 0.5:
                    best_candidate = new_candidate
                    best_fitness = new_fitness

        improved_candidates.append(
            (best_candidate, best_fitness)
        )

    # Sort according to fitness
    improved_candidates.sort(
        key=lambda x: x[1]
    )

    # Select best CNs while avoiding duplicates
    selected = []

    for candidate, fitness in improved_candidates:

        if candidate not in selected:
            selected.append(candidate)

        if len(selected) == NUM_CN:
            break

    # If insufficient CNs are selected
    if len(selected) < NUM_CN:

        remaining = [
            x for x in alive_nodes
            if x not in selected
        ]

        remaining.sort(
            key=lambda x:
            calculate_fitness(x, alive_nodes)
        )

        selected.extend(
            remaining[:NUM_CN - len(selected)]
        )

    return np.array(selected)


# ------------------------------------------------------------
# 10. CLUSTER ASSIGNMENT
# ------------------------------------------------------------

def assign_clusters(alive_nodes, control_nodes):

    clusters = {
        cn: [] for cn in control_nodes
    }

    for node in alive_nodes:

        if node in control_nodes:
            continue

        distances = DIST[node, control_nodes]

        # Select nearest CN
        cn = control_nodes[
            np.argmin(distances)
        ]

        clusters[cn].append(node)

    return clusters


# ------------------------------------------------------------
# 11. ENERGY CONSUMPTION
# ------------------------------------------------------------

def consume_energy(alive_nodes, control_nodes, clusters):

    new_energy = energy.copy()

    # ----------------------------------------
    # Sensor -> Control Node transmission
    # ----------------------------------------

    for cn, members in clusters.items():

        for node in members:

            d = DIST[node, cn]

            # Optical communication energy
            optical_loss = (
                1.0
                + FSO_DISTANCE_FACTOR * d ** 2
            )

            tx_energy = (
                PACKET_SIZE * E_ELEC
                + PACKET_SIZE * E_AMP * d ** 2
            )

            tx_energy *= optical_loss

            # Data aggregation at CN
            aggregation_energy = (
                PACKET_SIZE * E_DA
            )

            total = (
                tx_energy
                + aggregation_energy
            )

            new_energy[node] -= total

    # ----------------------------------------
    # CN -> SDN Control Server
    # ----------------------------------------

    for cn in control_nodes:

        d_server = np.linalg.norm(
            positions[cn] - CONTROL_SERVER
        )

        server_energy = (
            FSO_BASE_ENERGY
            + FSO_DISTANCE_FACTOR *
            d_server ** 2
        )

        new_energy[cn] -= server_energy

    # ----------------------------------------
    # Background underwater energy overhead
    # ----------------------------------------

    active_count = len(alive_nodes)

    background_energy = (
        0.00045
        + 0.0000007 * active_count
    )

    for node in alive_nodes:

        # Small sensing/processing expenditure
        sensing_energy = (
            background_energy
            * np.random.uniform(0.8, 1.2)
        )

        new_energy[node] -= sensing_energy

    # Prevent negative energy
    new_energy = np.maximum(
        new_energy,
        0
    )

    return new_energy


# ------------------------------------------------------------
# 12. MAIN SACO-CA SIMULATION
# ------------------------------------------------------------

for current_iteration in range(MAX_ITER):

    alive_nodes = np.where(
        energy > 0
    )[0]

    # Stop if network has completely died
    if len(alive_nodes) == 0:

        alive_history.append(0)
        dead_history.append(N)
        residual_energy_history.append(0)
        cn_history.append(0)

        continue

    # ----------------------------------------
    # SACO-CA CN selection
    # ----------------------------------------

    control_nodes = select_control_nodes(
        alive_nodes
    )

    # ----------------------------------------
    # Cluster formation
    # ----------------------------------------

    clusters = assign_clusters(
        alive_nodes,
        control_nodes
    )

    # ----------------------------------------
    # Energy consumption
    # ----------------------------------------

    energy[:] = consume_energy(
        alive_nodes,
        control_nodes,
        clusters
    )

    # ----------------------------------------
    # Record metrics
    # ----------------------------------------

    alive = np.sum(
        energy > 0
    )

    dead = N - alive

    residual = np.sum(energy)

    alive_history.append(alive)
    dead_history.append(dead)
    residual_energy_history.append(residual)
    cn_history.append(len(control_nodes))

    # ----------------------------------------
    # Lifetime indicators
    # ----------------------------------------

    if (
        first_dead_round is None
        and dead > 0
    ):
        first_dead_round = (
            current_iteration + 1
        )

    if (
        half_dead_round is None
        and dead >= N / 2
    ):
        half_dead_round = (
            current_iteration + 1
        )

    if alive > 0:
        last_alive_round = (
            current_iteration + 1
        )


